"""Record evidence-backed demonstrations by calling the real API on a fresh instance.

    python backend/scripts/run_demos.py     -> writes docs/DEMONSTRATIONS.md

Output reflects whichever generator is active (mock unless ANTHROPIC_API_KEY is set)
and is labelled accordingly. Nothing in the output file is hand-written.
"""
from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
os.environ["DATA_DIR"] = tempfile.mkdtemp(prefix="docqa-demo-")
os.environ["SEED_TEST_FIXTURES"] = "true"

DEMOS = [
    ("Direct answer", "emma", "How long is a password reset link valid?"),
    ("Paraphrase", "emma", "I forgot my login password"),
    ("Exact error code", "emma", "How do I fix error E104?"),
    ("Version-sensitive (no version given)", "sam", "What is the maximum upload size?"),
    ("Version-sensitive (version given)", "sam", "What is the maximum upload size in version 3?"),
    ("Genuine contradiction (test fixtures)", "emma", "How long before an idle web session is signed out?"),
    ("Partially answerable", "emma", "Can the reset link expiry be extended?"),
    ("Unsupported question", "emma", "What is the office parking policy for visitors?"),
    ("Authorization: Sales asks an HR-only question", "sam", "What is the salary band for L3?"),
    ("Authorization: HR asks the same question", "hana", "What is the salary band for L3?"),
    ("Document-based prompt injection (test fixture)", "sam", "How do I enable dark mode?"),
]


def main() -> None:
    from fastapi.testclient import TestClient

    from app.config import settings
    from app.main import app

    lines = ["# Demonstrations", ""]
    with TestClient(app) as c:
        health = c.get("/api/health").json()
        if health["mock_mode"]:
            lines += ["> Recorded in **MOCK MODE** (no model credentials were available): answer text is extracted verbatim "
                      "from evidence by a deterministic heuristic, not generated by an LLM. Retrieval, authorization, "
                      "citation validation, conflict detection and response-state logic are the real application code.", ""]
        else:
            lines += [f"> Recorded with `{health['model']}`.", ""]
        lines += [f"Embedding backend: `{health['embedding_backend']}`. Generated by `backend/scripts/run_demos.py`.", ""]
        tokens = {}
        for n, (title, user, q) in enumerate(DEMOS, 1):
            if user not in tokens:
                t = c.post("/api/auth/login", json={"username": user, "password": settings.demo_password}).json()["token"]
                tokens[user] = {"Authorization": f"Bearer {t}"}
            r = c.post("/api/ask", headers=tokens[user], json={"question": q}).json()
            lines += [f"## {n}. {title}", "", f"**User:** `{user}` · **Question:** {q}", "",
                      f"**State:** `{r['state']}`", ""]
            if r["message"]:
                lines += [f"> {r['message']}", ""]
            if r["clarification_question"]:
                lines += [f"**Clarification asked:** {r['clarification_question']}", ""]
            for conf in r["conflicts"]:
                lines += [f"**Conflict ({conf['kind']}):** {conf['description']}", ""]
            for s in r["answer"]:
                text = s["text"].replace("\n", " / ")
                lines.append(f"- {text} " + "".join(f"[{n}]" for n in s["citations"]))
            if r["answer"]:
                lines.append("")
            for m in r["missing_information"]:
                lines += [f"**Missing:** {m}", ""]
            for cit in r["citations"]:
                where = ", ".join(x for x in [cit["section"], f"page {cit['page']}" if cit["page"] else None,
                                              f"v{cit['product_version']}" if cit["product_version"] else None] if x)
                lines.append(f"- [{cit['number']}] **{cit['title']}** ({where}) `{cit['chunk_id']}` — \"{cit['excerpt'].replace(chr(10), ' / ')}\"")
            if r["citations"]:
                lines.append("")
            flags = r["security_flags"] + [w for w in r["warnings"] if not w.startswith("MOCK MODE")]
            for f in flags:
                lines.append(f"- _{f}_")
            lines.append("")
    out = ROOT / "docs" / "DEMONSTRATIONS.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
